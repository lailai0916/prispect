import { chromium } from '/workspace/prispect-improve/node_modules/playwright/index.mjs';
import { writeFile } from 'node:fs/promises';
const root = '/workspace/prispect-improve/docs/competitive-research/evidence/mingcha';
const browser = await chromium.launch({ executablePath:'/usr/bin/chromium', headless:true, args:['--no-sandbox'] });
const context = await browser.newContext({ viewport:{width:1440,height:1000}, reducedMotion:'reduce' });
const page = await context.newPage();
const errors=[], apiRequests=[], failures=[];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => {if(request.url().includes('/api/')) apiRequests.push(request.url());});
const result={executionTime:new Date().toISOString(), mode:'Synthetic full CompanyResearchReport; no real query', checks:[]};
function check(name, passed, evidence) { result.checks.push({name, passed, evidence}); if(!passed) failures.push(name); }
await page.goto('http://127.0.0.1:5405/docs/competitive-research/evidence/mingcha/report-controls-preview.html');
const report=page.getByTestId('company-research-report');
await report.waitFor();
const count=report.locator('.report-evidence-count');
await count.filter({hasText:'0/5'}).waitFor();
const expand=report.getByRole('button',{name:'展开核验区',exact:true});
const collapse=report.getByRole('button',{name:'收起核验区',exact:true});
const initialRun=await page.getByTestId('run-json').textContent();
const readingBefore=await report.locator('.source-trust-summary').innerText();
check('initial retained content collapsed', await collapse.isDisabled(), await count.innerText());
await page.screenshot({path:`${root}/report-controls-before.png`,fullPage:true});
await page.locator('#external-same-class > summary').click();
await expand.focus();
await page.keyboard.press('Enter');
await count.filter({hasText:'5/5'}).waitFor();
const inventory=()=>report.locator('details').evaluateAll(entries=>entries.map(el=>({id:el.id,class:el.className,open:el.open,label:el.querySelector('summary')?.innerText})));
check('keyboard Enter expands actual five review disclosures', (await inventory()).filter(el=>el.open).length===5, await inventory());
check('expand affects one report only', await page.locator('#external-same-class').evaluate(el=>el.open) && await page.locator('#company-full-report').evaluate(el=>!el.open) && await page.locator('#company-public-signals').evaluate(el=>!el.open), 'Outside matching class stays open; outside complete analysis and discussions stay closed.');
check('opening source list does not change reading status', readingBefore===await report.locator('.source-trust-summary').innerText(), await report.locator('.source-trust-summary').innerText());
await page.screenshot({path:`${root}/report-controls-after.png`,fullPage:true});
await report.locator('#company-research-framework > summary').focus();
await page.keyboard.press('Enter');
await count.filter({hasText:'4/5'}).waitFor();
check('manual keyboard fold updates mixed count', await expand.isEnabled() && await collapse.isEnabled(), await count.innerText());
await page.evaluate(()=>{const el=document.createElement('details');el.id='unrelated-report-detail';el.open=true;el.innerHTML='<summary>未列入核验范围</summary><p>独立内容</p>';document.querySelector('[data-report-evidence-scope]').append(el);});
await collapse.focus();
await page.keyboard.press('Space');
await count.filter({hasText:'0/5'}).waitFor();
check('keyboard Space collapses only review whitelist', (await inventory()).filter(el=>el.open).map(el=>el.id).join(',')==='unrelated-report-detail' && await page.locator('#external-same-class').evaluate(el=>el.open), await inventory());
check('local controls leave saved data unchanged', initialRun===await page.getByTestId('run-json').textContent(), 'Same serialized input/context/report before and after view controls.');
const scopeChecks=[];
for(const scenario of ['previous','current','other-record','other-year','other-issuer','missing','current']) {
  const currentExpand=report.getByRole('button',{name:'展开核验区',exact:true});
  if(await currentExpand.isEnabled()) await currentExpand.click();
  await page.getByRole('combobox',{name:'场景',exact:true}).selectOption(scenario);
  await page.waitForFunction(()=>{const text=document.querySelector('.report-evidence-count')?.textContent;return text?.includes('核验区 0/');});
  const entry={scenario,count:await count.innerText(),notice:await report.locator('.report-evidence-note').innerText(),unrelatedStillOpen:await page.locator('#unrelated-report-detail').evaluate(el=>el.open)};
  scopeChecks.push(entry);
}
check('current, previous, record, year and issuer scopes reset', scopeChecks.every(el=>el.count.startsWith('核验区 0/') && el.notice.includes('已重置') && el.unrelatedStillOpen),scopeChecks);
check('disclosure controls never invoke research', apiRequests.length===0 && await page.getByTestId('refresh-count').innerText()==='研究调用 0',{apiRequests,refreshCount:await page.getByTestId('refresh-count').innerText()});
await report.getByRole('button',{name:'展开核验区',exact:true}).click();
await page.getByRole('button',{name:'切换主题',exact:true}).click();
await page.screenshot({path:`${root}/report-controls-dark.png`,fullPage:true});
const mobile=[];
for(const width of [375,320]){
  await page.setViewportSize({width,height:812});
  if(width===320) await page.getByRole('combobox',{name:'语言',exact:true}).selectOption('en');
  const item=await page.evaluate(()=>({viewport:innerWidth,documentWidth:document.documentElement.scrollWidth,buttons:[...document.querySelectorAll('.report-evidence-actions button')].map(el=>({width:el.getBoundingClientRect().width,height:el.getBoundingClientRect().height}))}));
  mobile.push(item);
  await page.screenshot({path:`${root}/report-controls-mobile-${width}.png`,fullPage:true});
}
check('narrow layout and keyboard controls remain usable', mobile.every(item=>item.documentWidth===item.viewport && item.buttons.every(button=>button.height>=44)),mobile);
await report.getByRole('button',{name:'Collapse review sections',exact:true}).click();
await page.emulateMedia({media:'print'});
result.print={controlDisplay:await report.locator('.report-evidence-controls').evaluate(el=>getComputedStyle(el).display),sourcePagedDisplay:await report.locator('.source-trust-detail').evaluate(el=>getComputedStyle(el).display),sourcePrintDisplay:await report.locator('.source-trust-print').evaluate(el=>getComputedStyle(el).display),frameworkVisibility:await report.locator('#company-research-framework').evaluate(el=>getComputedStyle(el,'::details-content').contentVisibility),requestsVisibility:await report.locator('#company-review-requests').evaluate(el=>getComputedStyle(el,'::details-content').contentVisibility),collapsedStill:await report.locator('#company-research-framework').evaluate(el=>!el.open)};
await page.pdf({path:`${root}/report-controls-print.pdf`,format:'A4',printBackground:true});
check('print reveals retained review content without changing disclosure state', result.print.controlDisplay==='none' && result.print.sourcePagedDisplay==='none' && result.print.sourcePrintDisplay==='block' && result.print.frameworkVisibility==='visible' && result.print.requestsVisibility==='visible' && result.print.collapsedStill,result.print);
check('no browser errors',errors.length===0,errors);
result.errors=errors;result.apiRequests=apiRequests;result.failures=failures;
await writeFile(`${root}/report-controls-results.json`,JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
await browser.close();
if(failures.length)process.exitCode=1;
